const dictionaries: Record<Language, Record<MessageKey, string>> = { en, zh }

interface LocaleValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: MessageKey, vars?: Record<string, string | number>) => string
}

const LanguageContext = createContext<LocaleValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [stored, setStored] = usePersistentState<Language>(
    'jj-language',
    'zh',
    (value) => (value === 'en' ? 'en' : 'zh'),
  )
  const language: Language = stored === 'en' ? 'en' : 'zh'

  const setLanguage = useCallback(
    (next: Language) => {
      setStored(next)
    },
    [setStored],
  )

  const t = useCallback(
    (key: MessageKey, vars?: Record<string, string | number>) => {
      const template = dictionaries[language][key] ?? en[key] ?? key
      if (!vars) return template
      return template.replace(/\{(\w+)\}/g, (match, name: string) => {
        const value = vars[name]
        return value === undefined ? match : String(value)
      })
    },
    [language],
  )

  useEffect(() => {
    const root = document.documentElement
    root.lang = language === 'zh' ? 'zh-CN' : 'en'
    document.title = language === 'zh' ? '见界 · 私人影院' : 'Jianjie · Private Cinema'
    if (isDesktopApp) {
      void import('@tauri-apps/api/window')
        .then(({ getCurrentWindow }) => getCurrentWindow().setTitle(document.title))
        .catch(() => undefined)
    }
  }, [language])

  const value = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t],
  )

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useI18n must be used inside LanguageProvider')
  return context
}
